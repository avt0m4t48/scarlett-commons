//! Track B's emitter: one x86-64 function to Rust source that runs over a register-state context.
//!
//! The source is generated on the player's machine from their own copy of a title and built there; nothing it
//! produces is committed. What it covers is the single definition track B and the census use: an instruction is
//! covered exactly when [`emit_instruction`] can translate it.
//!
//! The generated function is `unsafe fn NAME(c: &mut Ctx)` over [`PRELUDE`]'s `Ctx`: the sixteen general-purpose
//! registers in encoding order, the CF, ZF, SF and OF flags, and `ret`, the return address a `ret` popped. Memory is the
//! process's own (the title's memory is mapped at its addresses), read and written unaligned. The body is a loop over
//! the function's instruction addresses, so branches inside the function are a change of `pc`.
//!
//! Covered today (v1): mov, movzx, movsx, movsxd, lea, add, sub, and, or, xor, cmp, test, inc, dec, neg, not,
//! shl/shr/sar on 32- and 64-bit operands, jcc (without parity) and jmp to an instruction of the same function, ret,
//! push and pop of 64-bit values, setcc, cmovcc, xchg of two registers, nop; general-purpose registers (not AH-DH) and
//! memory without FS/GS. Not yet: calls, the remaining integer instructions, SIMD. Shifts by a count above 1 leave OF
//! as for a count of 1, where the CPU leaves it undefined.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use iced_x86::{
    ConditionCode, Decoder, DecoderOptions, FlowControl, Instruction, Mnemonic, OpKind, Register,
};

/// The context and helpers every generated file starts with.
pub const PRELUDE: &str = r#"// Generated by commons-recomp-emit on the player's machine. Not to be committed.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Ctx {
    pub r: [u64; 16],
    pub cf: bool,
    pub zf: bool,
    pub sf: bool,
    pub of: bool,
    pub ret: u64,
}
#[inline(always)]
fn mask(n: u32) -> u64 { if n >= 8 { u64::MAX } else { (1u64 << (n * 8)) - 1 } }
#[inline(always)]
fn sx(v: u64, n: u32) -> u64 { let s = 64 - n * 8; (((v << s) as i64) >> s) as u64 }
#[inline(always)]
fn sign(v: u64, n: u32) -> bool { (v >> (n * 8 - 1)) & 1 == 1 }
#[inline(always)]
unsafe fn ld(a: u64, n: u32) -> u64 {
    unsafe {
        match n {
            1 => (a as *const u8).read_unaligned() as u64,
            2 => (a as *const u16).read_unaligned() as u64,
            4 => (a as *const u32).read_unaligned() as u64,
            _ => (a as *const u64).read_unaligned(),
        }
    }
}
#[inline(always)]
unsafe fn st(a: u64, n: u32, v: u64) {
    unsafe {
        match n {
            1 => (a as *mut u8).write_unaligned(v as u8),
            2 => (a as *mut u16).write_unaligned(v as u16),
            4 => (a as *mut u32).write_unaligned(v as u32),
            _ => (a as *mut u64).write_unaligned(v),
        }
    }
}
#[inline(always)]
fn wr(c: &mut Ctx, r: usize, n: u32, v: u64) {
    match n {
        8 => c.r[r] = v,
        4 => c.r[r] = v & 0xffff_ffff,
        _ => { let m = mask(n); c.r[r] = (c.r[r] & !m) | (v & m); }
    }
}
#[inline(always)]
fn szf(c: &mut Ctx, r: u64, n: u32) { c.zf = r & mask(n) == 0; c.sf = sign(r, n); }
"#;

fn gpr(r: Register) -> Option<(usize, u32)> {
    if matches!(r, Register::AH | Register::CH | Register::DH | Register::BH) || !r.is_gpr() {
        return None;
    }
    let full = r.full_register();
    let index = full as usize - Register::RAX as usize;
    (index < 16).then_some((index, r.size() as u32))
}

fn address(i: &Instruction) -> Option<String> {
    if matches!(i.memory_segment(), Register::FS | Register::GS) {
        return None;
    }
    let disp = i.memory_displacement64();
    if i.memory_base() == Register::RIP {
        return Some(format!("{disp:#x}u64"));
    }
    let mut parts = Vec::new();
    if i.memory_base() != Register::None {
        let (b, n) = gpr(i.memory_base())?;
        if n != 8 {
            return None;
        }
        parts.push(format!("c.r[{b}]"));
    }
    if i.memory_index() != Register::None {
        let (x, n) = gpr(i.memory_index())?;
        if n != 8 {
            return None;
        }
        parts.push(format!("c.r[{x}].wrapping_mul({})", i.memory_index_scale()));
    }
    parts.push(format!("{disp:#x}u64"));
    let mut expr = parts.remove(0);
    for p in parts {
        expr = format!("{expr}.wrapping_add({p})");
    }
    Some(expr)
}

/// The value of operand `n` at `size` bytes, as a Rust expression.
fn read(i: &Instruction, n: u32, size: u32) -> Option<String> {
    match i.op_kind(n) {
        OpKind::Register => {
            let (r, rn) = gpr(i.op_register(n))?;
            Some(format!("(c.r[{r}] & mask({rn}))"))
        }
        OpKind::Memory => Some(format!("ld({}, {size})", address(i)?)),
        OpKind::Immediate8
        | OpKind::Immediate16
        | OpKind::Immediate32
        | OpKind::Immediate64
        | OpKind::Immediate8to16
        | OpKind::Immediate8to32
        | OpKind::Immediate8to64
        | OpKind::Immediate32to64 => Some(format!("({:#x}u64 & mask({size}))", i.immediate(n))),
        _ => None,
    }
}

/// A statement that writes `value` to operand 0 at `size` bytes.
fn write(i: &Instruction, size: u32, value: &str) -> Option<String> {
    match i.op_kind(0) {
        OpKind::Register => {
            let (r, _) = gpr(i.op_register(0))?;
            Some(format!("wr(c, {r}, {size}, {value});"))
        }
        OpKind::Memory => Some(format!("st({}, {size}, {value});", address(i)?)),
        _ => None,
    }
}

fn condition(cc: ConditionCode) -> Option<&'static str> {
    Some(match cc {
        ConditionCode::o => "c.of",
        ConditionCode::no => "!c.of",
        ConditionCode::b => "c.cf",
        ConditionCode::ae => "!c.cf",
        ConditionCode::e => "c.zf",
        ConditionCode::ne => "!c.zf",
        ConditionCode::be => "(c.cf || c.zf)",
        ConditionCode::a => "!(c.cf || c.zf)",
        ConditionCode::s => "c.sf",
        ConditionCode::ns => "!c.sf",
        ConditionCode::l => "(c.sf != c.of)",
        ConditionCode::ge => "(c.sf == c.of)",
        ConditionCode::le => "(c.zf || c.sf != c.of)",
        ConditionCode::g => "(!c.zf && c.sf == c.of)",
        _ => return None, // parity
    })
}

fn size_of_op0(i: &Instruction) -> Option<u32> {
    match i.op_kind(0) {
        OpKind::Register => gpr(i.op_register(0)).map(|(_, n)| n),
        OpKind::Memory => Some(i.memory_size().size() as u32),
        _ => None,
    }
}

/// The Rust statements for one instruction, ending with the next `pc` (or a return). `targets` are the instruction
/// addresses of the function, for branches. None when the instruction is not covered.
pub fn emit_instruction(i: &Instruction, targets: &BTreeSet<u64>) -> Option<String> {
    use Mnemonic::*;
    let next = format!("pc = {:#x};", i.next_ip());
    let mut s = String::new();
    match i.mnemonic() {
        Nop => {}
        Mov => {
            let n = size_of_op0(i)?;
            s += &write(i, n, &read(i, 1, n)?)?;
        }
        Movzx => {
            let n = size_of_op0(i)?;
            let m = if i.op_kind(1) == OpKind::Memory { i.memory_size().size() as u32 } else { gpr(i.op_register(1))?.1 };
            s += &write(i, n, &read(i, 1, m)?)?;
        }
        Movsx | Movsxd => {
            let n = size_of_op0(i)?;
            let m = if i.op_kind(1) == OpKind::Memory { i.memory_size().size() as u32 } else { gpr(i.op_register(1))?.1 };
            s += &write(i, n, &format!("(sx({}, {m}) & mask({n}))", read(i, 1, m)?))?;
        }
        Lea => {
            let n = size_of_op0(i)?;
            if i.op_kind(1) != OpKind::Memory {
                return None;
            }
            s += &write(i, n, &format!("({} & mask({n}))", address(i)?))?;
        }
        Add | Sub | Cmp | And | Or | Xor | Test => {
            let n = size_of_op0(i)?;
            let (a, b) = (read(i, 0, n)?, read(i, 1, n)?);
            let _ = write!(s, "let a = {a}; let b = {b}; ");
            match i.mnemonic() {
                Add => s += "let r = a.wrapping_add(b) & mask(N); c.cf = (a as u128 + b as u128) > mask(N) as u128; c.of = sign(!(a ^ b) & (a ^ r), N); ",
                Sub | Cmp => s += "let r = a.wrapping_sub(b) & mask(N); c.cf = a < b; c.of = sign((a ^ b) & (a ^ r), N); ",
                And | Test => s += "let r = a & b; c.cf = false; c.of = false; ",
                Or => s += "let r = a | b; c.cf = false; c.of = false; ",
                _ => s += "let r = a ^ b; c.cf = false; c.of = false; ",
            }
            s += "szf(c, r, N); ";
            if !matches!(i.mnemonic(), Cmp | Test) {
                s += &write(i, n, "r")?;
            }
            s = s.replace("N)", &format!("{n})"));
        }
        Inc | Dec => {
            let n = size_of_op0(i)?;
            let a = read(i, 0, n)?;
            let (op, ov) = if i.mnemonic() == Inc { ("wrapping_add", "!(a ^ 1) & (a ^ r)") } else { ("wrapping_sub", "(a ^ 1) & (a ^ r)") };
            let _ = write!(s, "let a = {a}; let r = a.{op}(1) & mask({n}); c.of = sign({ov}, {n}); szf(c, r, {n}); ");
            s += &write(i, n, "r")?;
        }
        Neg => {
            let n = size_of_op0(i)?;
            let a = read(i, 0, n)?;
            let _ = write!(s, "let a = {a}; let r = 0u64.wrapping_sub(a) & mask({n}); c.cf = a != 0; c.of = a == 1u64 << ({n} * 8 - 1); szf(c, r, {n}); ");
            s += &write(i, n, "r")?;
        }
        Not => {
            let n = size_of_op0(i)?;
            let a = read(i, 0, n)?;
            s += &write(i, n, &format!("(!{a} & mask({n}))"))?;
        }
        Shl | Shr | Sar => {
            let n = size_of_op0(i)?;
            if n < 4 {
                return None;
            }
            let bits = n * 8;
            let a = read(i, 0, n)?;
            let count = match i.op_kind(1) {
                OpKind::Register if i.op_register(1) == Register::CL => "(c.r[1] & 0xff)".to_string(),
                OpKind::Immediate8 => format!("{}u64", i.immediate(1) & 0xff),
                _ => return None,
            };
            let _ = write!(s, "let a = {a}; let k = {count} & {}; if k != 0 {{ ", bits - 1);
            match i.mnemonic() {
                Shl => { let _ = write!(s, "let r = (a << k) & mask({n}); c.cf = (a >> ({bits} - k)) & 1 == 1; c.of = sign(r, {n}) != c.cf; "); }
                Shr => { let _ = write!(s, "let r = a >> k; c.cf = (a >> (k - 1)) & 1 == 1; c.of = sign(a, {n}); "); }
                _ => { let _ = write!(s, "let w = sx(a, {n}) as i64; let r = ((w >> k) as u64) & mask({n}); c.cf = (w >> (k - 1)) & 1 == 1; c.of = false; "); }
            }
            let _ = write!(s, "szf(c, r, {n}); ");
            s += &write(i, n, "r")?;
            s += " }";
            // A count of 0 changes no flag and no value, but a 32-bit register destination is still written, so its
            // upper half is cleared (measured: `sar r10d, cl` with CL = 0).
            if n == 4 && i.op_kind(0) == OpKind::Register {
                s += " else { ";
                s += &write(i, n, "a")?;
                s += " }";
            }
        }
        Xchg => {
            if i.op_kind(0) != OpKind::Register || i.op_kind(1) != OpKind::Register {
                return None;
            }
            let (x, n) = gpr(i.op_register(0))?;
            let (y, m) = gpr(i.op_register(1))?;
            if n != m {
                return None;
            }
            let _ = write!(s, "let t = c.r[{x}] & mask({n}); let u = c.r[{y}] & mask({n}); wr(c, {x}, {n}, u); wr(c, {y}, {n}, t);");
        }
        Push => {
            let v = read(i, 0, 8)?;
            if matches!(i.op_kind(0), OpKind::Register) && gpr(i.op_register(0))?.1 != 8 {
                return None;
            }
            let _ = write!(s, "let v = {v}; c.r[4] = c.r[4].wrapping_sub(8); st(c.r[4], 8, v);");
        }
        Pop => {
            if i.op_kind(0) != OpKind::Register {
                return None;
            }
            let (r, n) = gpr(i.op_register(0))?;
            if n != 8 {
                return None;
            }
            let _ = write!(s, "let v = ld(c.r[4], 8); c.r[4] = c.r[4].wrapping_add(8); c.r[{r}] = v;");
        }
        Ret => {
            if i.op_count() != 0 {
                return None;
            }
            return Some("c.ret = ld(c.r[4], 8); c.r[4] = c.r[4].wrapping_add(8); return;".into());
        }
        Jmp => {
            if !matches!(i.op0_kind(), OpKind::NearBranch64) || !targets.contains(&i.near_branch_target()) {
                return None;
            }
            return Some(format!("pc = {:#x};", i.near_branch_target()));
        }
        _ => {
            let name = format!("{:?}", i.mnemonic());
            let cc = condition(i.condition_code())?;
            if i.flow_control() == FlowControl::ConditionalBranch && name.starts_with('J') {
                if !matches!(i.op0_kind(), OpKind::NearBranch64) || !targets.contains(&i.near_branch_target()) {
                    return None;
                }
                return Some(format!("pc = if {cc} {{ {:#x} }} else {{ {:#x} }};", i.near_branch_target(), i.next_ip()));
            } else if name.starts_with("Set") {
                s += &write(i, 1, &format!("({cc} as u64)"))?;
            } else if name.starts_with("Cmov") {
                let n = size_of_op0(i)?;
                let (r, _) = gpr(i.op_register(0))?;
                let v = read(i, 1, n)?;
                // A 32-bit cmov clears the upper half of its destination even when the condition is false.
                let _ = write!(s, "if {cc} {{ wr(c, {r}, {n}, {v}); }} else {{ wr(c, {r}, {n}, c.r[{r}]); }}");
            } else {
                return None;
            }
        }
    }
    s.push(' ');
    s += &next;
    Some(s)
}

/// Whether the emitter covers this instruction (the census uses this one definition). Branch targets are not known
/// here, so a direct branch counts as covered; [`emit_function`] refuses one that leaves the function.
pub fn supported(i: &Instruction) -> bool {
    let mut all = BTreeSet::new();
    if matches!(i.op0_kind(), OpKind::NearBranch64) {
        all.insert(i.near_branch_target());
    }
    emit_instruction(i, &all).is_some()
}

/// Every instruction of one function's bytes at `ip`.
pub fn decode(code: &[u8], ip: u64) -> Vec<Instruction> {
    let mut d = Decoder::with_ip(64, code, ip, DecoderOptions::NONE);
    let mut out = Vec::new();
    while d.can_decode() {
        out.push(d.decode());
    }
    out
}

/// The Rust source of one function, or the address and text of the first instruction it does not cover.
pub fn emit_function(name: &str, code: &[u8], ip: u64) -> Result<String, String> {
    let insns = decode(code, ip);
    if insns.is_empty() {
        return Err("no instructions".into());
    }
    let targets: BTreeSet<u64> = insns.iter().map(Instruction::ip).collect();
    let mut body = String::new();
    for i in &insns {
        if i.is_invalid() {
            return Err(format!("{:#x}: undecodable", i.ip()));
        }
        let Some(stmt) = emit_instruction(i, &targets) else {
            return Err(format!("{:#x}: not covered: {i}", i.ip()));
        };
        let _ = writeln!(body, "            {:#x} => {{ {stmt} }} // {i}", i.ip());
    }
    Ok(format!(
        "#[allow(unused_mut, unused_variables, unused_assignments, unreachable_code, clippy::all)]\npub unsafe fn {name}(c: &mut Ctx) {{\n    let mut pc: u64 = {ip:#x};\n    loop {{\n        unsafe {{ match pc {{\n{body}            _ => panic!(\"pc {{pc:#x}} outside {name}\"),\n        }} }}\n    }}\n}}\n"
    ))
}
